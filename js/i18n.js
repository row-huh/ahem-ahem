// ?lang=ur in the address wins over the remembered choice, so links can be shared in Urdu.
const asked = typeof location === 'undefined' ? null : new URLSearchParams(location.search).get('lang');
let lang = (asked || localStorage.getItem('lang')) === 'ur' ? 'ur' : 'en';

export const getLang = () => lang;
export function setLang(next) {
  lang = next;
  localStorage.setItem('lang', next);
}
export function t(key, vars = {}) {
  return (TEXT[lang][key] ?? TEXT.en[key] ?? key).replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
}
// Stop and line names are stored as [English, Urdu].
export const pick = (pair) => pair[lang === 'ur' ? 1 : 0] || pair[0];

// Distances are rounded so they read as estimates, not measurements.
export function dist(metres) {
  if (metres < 950) return t('m', { n: Math.max(50, Math.round(metres / 50) * 50) });
  const km = metres / 1000;
  return t('km', { n: km < 10 ? km.toFixed(1) : Math.round(km) });
}
